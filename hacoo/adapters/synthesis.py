# ---------------------------------------------------------- FE-1/FE-2 报告解析 (纯函数)
# 输入 report_qor 文本 -> 输出归一化 metrics dict
# {wns, tns, area, leakage, total_power}; 解析不到的字段为 None。
# 单位: wns/tns 为库时间单位 (ns); area 为 um^2; power 为 mW。

def parse_genus_qor(report: str) -> Dict[str, Optional[float]]:
    """Genus report_qor: WNS/TNS 取 setup 列 (每行首列数值);
    面积取 Total Cell Area; 功耗取汇总段的 Leakage/Total Power。"""
    wns_m = re.search(r"(?m)^\s*WNS[^:]*:\s*(-?\d+\.?\d*)", report)
    tns_m = re.search(r"(?m)^\s*TNS[^:]*:\s*(-?\d+\.?\d*)", report)
    area_m = re.search(r"Total\s+Cell\s+Area[^:]*:\s*([\d.]+)", report, re.IGNORECASE)
    leak_m = re.search(r"Leakage\s+Power[^:]*:\s*([\d.]+)", report, re.IGNORECASE)
    tot_m = re.search(r"Total\s+Power[^:]*:\s*([\d.]+)", report, re.IGNORECASE)
    return {"wns": float(wns_m.group(1)) if wns_m else None,
            "tns": float(tns_m.group(1)) if tns_m else None,
            "area": float(area_m.group(1)) if area_m else None,
            "leakage": float(leak_m.group(1)) if leak_m else None,
            "total_power": float(tot_m.group(1)) if tot_m else None}


def parse_dc_qor(report: str) -> Dict[str, Optional[float]]:
    """DC report_qor (+ report_power 追加段): WNS/TNS 取 Critical Path
    Slack / Total Negative Slack; 面积取 Cell Area 汇总行; 功耗取
    report_power 末行 Total 的第 3/4 列 (leakage/total)。"""
    wns_m = re.search(r"Critical\s+Path\s+Slack\s*[:=]?\s*(-?\d+\.?\d*)",
                      report, re.IGNORECASE)
    tns_m = re.search(r"Total\s+Negative\s+Slack\s*[:=]?\s*(-?\d+\.?\d*)",
                      report, re.IGNORECASE)
    area_m = re.search(r"(?m)^\s*Cell\s+Area\s*[:=]?\s*([\d.]+)", report)
    power_m = re.search(
        r"(?m)^\s*Total\s+(-?\d+\.?\d*)\s+(-?\d+\.?\d*)\s+(-?\d+\.?\d*)\s+(-?\d+\.?\d*)",
        report)
    return {"wns": float(wns_m.group(1)) if wns_m else None,
            "tns": float(tns_m.group(1)) if tns_m else None,
            "area": float(area_m.group(1)) if area_m else None,
            "leakage": float(power_m.group(3)) if power_m else None,
            "total_power": float(power_m.group(4)) if power_m else None}


class _SynthesisTclAdapter(ToolAdapter):
    """公共骨架: 持久 shell 管理 + 设计/编译状态; 工具命令语义由子类封装 (T2)。"""

    _BIN_DEFAULTS: List[str] = []
    _SHELL_ARGS: List[str] = []
    _MOCK_CANNED: Dict[str, Any] = {}

    def __init__(self) -> None:
        self._shell: Optional[TclShell] = None
        self.design: Dict[str, Any] = {}
        self.compile_history: List[Dict[str, Any]] = []

    def _session(self) -> TclShell:
        if self._shell is None:
            if os.environ.get("HACOO_%s_MOCK" % self.tool_name.upper()) == "1":
                self._shell = MockTclShell(self.tool_name, canned=self._MOCK_CANNED)
            else:
                exe = resolve_binary(self.tool_name, self._BIN_DEFAULTS)
                self._shell = TclShell(exe, self._SHELL_ARGS)
        return self._shell

    def __del__(self) -> None:
        if self._shell:
            self._shell.close()

    def _require_design(self) -> None:
        if not self.design:
            raise RuntimeError("no design elaborated; call api_synth_elaborate first")

    @api_method(capability="read", description="Dump current synthesis session state.")
    def api_get_design_state(self) -> Dict[str, Any]:
        return {"data": {"design": self.design or None,
                         "compile_history": list(self.compile_history)}}


class GenusAdapter(_SynthesisTclAdapter):
    """Cadence Genus (genus -legacy_ui): read_hdl/syn_generic/syn_map/syn_opt 系。"""

    tool_name = "genus"
    _BIN_DEFAULTS = ["genus"]
    _SHELL_ARGS = ["-legacy_ui"]
    _MOCK_CANNED = _GENUS_MOCK_CANNED

    @api_method(capability="write",
                description="Read RTL files and elaborate the top module (Genus read_hdl + elaborate).")
    def api_synth_elaborate(self, files: list, top: str) -> Dict[str, Any]:
        """read_hdl {<files>} 读入 RTL + elaborate <top> 展开顶层设计。
        命令语义已查证: Genus legacy UI 的 read_hdl 接受花括号文件列表,
        elaborate 解析并链接设计。"""
        genus = self._session()
        genus.cmd("read_hdl {%s}" % " ".join(files), timeout=1800)
        out = genus.cmd("elaborate %s" % top, timeout=1800)
        if "Error" in out:
            raise RuntimeError("elaborate failed:\n%s" % out[-1500:])
        self.design = {"files": list(files), "top": top}
        return {"data": {"elaborated": True, "top": top, "files": len(files)},
                "text": "design '%s' elaborated in Genus (%d files)" % (top, len(files))}

    @api_method(capability="write",
                description="Synthesize to mapped gates: syn_generic/syn_map/syn_opt at given effort; extra_tcl runs pre-compile strategy commands.")
    def api_synth_compile(self, effort: str = "medium",
                          extra_tcl: Optional[str] = None) -> Dict[str, Any]:
        """syn_generic -effort <e> + syn_map -effort <e> + syn_opt 三段综合。
        命令语义已查证: -effort (low|medium|high) 仅 syn_generic/syn_map
        支持; syn_opt 为映射后增量优化 (无 effort 选项)。
        extra_tcl (FE-3): 编译前的策略客制化命令 (整条注入, 与 icc2
        extra_tcl 先例一致), 如 ungroup -flatten / set_db
        boundary_optimize 等 synth-convergence skill 的迭代策略。"""
        self._require_design()
        if effort not in _EFFORTS:
            raise ValueError("effort must be one of %s" % list(_EFFORTS))
        genus = self._session()
        t0 = time.time()
        if extra_tcl:
            genus.cmd(extra_tcl, timeout=1800)
        commands = ["syn_generic -effort %s" % effort,
                    "syn_map -effort %s" % effort,
                    "syn_opt"]
        for command in commands:
            out = genus.cmd(command, timeout=7200)
            if "Error" in out:
                raise RuntimeError("synthesis failed (%s):\n%s" % (command, out[-1500:]))
        record = {"effort": effort, "elapsed_s": round(time.time() - t0, 1)}
        if extra_tcl:
            record["extra_tcl"] = extra_tcl
        self.compile_history.append(record)
        return {"data": dict(record, compiles_done=len(self.compile_history)),
                "text": "genus compile done (effort=%s) in %.1fs"
                        % (effort, record["elapsed_s"])}

    @api_method(capability="read",
                description="report_qor: normalized WNS/TNS (ns) / area (um^2) / leakage & total power (mW).")
    def api_report_qor(self) -> Dict[str, Any]:
        """Genus report_qor 自带 timing/area/power 汇总, 解析为五字段。"""
        self._require_design()
        report = self._session().cmd("report_qor", timeout=600)
        data = dict(parse_genus_qor(report), top=self.design.get("top"),
                    commands=["report_qor"])
        return {"data": data, "text": report[-3000:]}


class DCAdapter(_SynthesisTclAdapter):
    """Synopsys Design Compiler (dc_shell-t): analyze/elaborate/compile_ultra 系。"""

    tool_name = "dc_shell"
    _BIN_DEFAULTS = ["dc_shell-t"]
    _MOCK_CANNED = _DC_MOCK_CANNED

    @api_method(capability="write",
                description="Analyze RTL files and elaborate the top module (DC analyze + elaborate).")
    def api_synth_elaborate(self, files: list, top: str) -> Dict[str, Any]:
        """analyze -format verilog {<files>} 分析 RTL + elaborate <top>。
        命令语义已查证: DC 的两步读入 (analyze 进库 -> elaborate 链接),
        与 Genus 的 read_hdl 单步不同。"""
        dc = self._session()
        dc.cmd("analyze -format verilog {%s}" % " ".join(files), timeout=1800)
        out = dc.cmd("elaborate %s" % top, timeout=1800)
        if "Error" in out:
            raise RuntimeError("elaborate failed:\n%s" % out[-1500:])
        self.design = {"files": list(files), "top": top}
        return {"data": {"elaborated": True, "top": top, "files": len(files)},
                "text": "design '%s' elaborated in Design Compiler (%d files)"
                        % (top, len(files))}

    @api_method(capability="write",
                description="Compile to mapped gates: compile_ultra family with effort convention; extra_tcl runs pre-compile strategy commands.")
    def api_synth_compile(self, effort: str = "medium",
                          extra_tcl: Optional[str] = None) -> Dict[str, Any]:
        """effort -> 命令约定 (T2, 注释说明): compile_ultra 无 -effort 选项,
        本 adapter 约定 low 回退经典 compile -map_effort low, medium 为
        单轮 compile_ultra, high 追加 compile_ultra -incremental 二轮优化。
        extra_tcl (FE-3): 编译前的策略客制化命令 (整条注入, 与 Genus /
        icc2 extra_tcl 先例一致), 如 ungroup / set_boundary_optimization。"""
        self._require_design()
        if effort not in _EFFORTS:
            raise ValueError("effort must be one of %s" % list(_EFFORTS))
        base = {"low": ["compile -map_effort low"],
                "medium": ["compile_ultra"],
                "high": ["compile_ultra", "compile_ultra -incremental"]}[effort]
        dc = self._session()
        t0 = time.time()
        if extra_tcl:
            dc.cmd(extra_tcl, timeout=1800)
        commands = base
        for command in commands:
            out = dc.cmd(command, timeout=7200)
            if "Error" in out:
                raise RuntimeError("compile failed (%s):\n%s" % (command, out[-1500:]))
        record = {"effort": effort, "elapsed_s": round(time.time() - t0, 1)}
        if extra_tcl:
            record["extra_tcl"] = extra_tcl
        self.compile_history.append(record)
        return {"data": dict(record, compiles_done=len(self.compile_history)),
                "text": "dc compile done (effort=%s) in %.1fs"
                        % (effort, record["elapsed_s"])}

    @api_method(capability="read",
                description="report_qor + report_power: normalized WNS/TNS (lib units) / area (um^2) / leakage & total power (mW).")
    def api_report_qor(self) -> Dict[str, Any]:
        """DC report_qor 不含功耗段, 追加 report_power 并拼接解析 (T2 封装)。"""
        self._require_design()
        dc = self._session()
        qor = dc.cmd("report_qor", timeout=600)
        power = dc.cmd("report_power", timeout=600)
        report = qor + "\n" + power
        data = dict(parse_dc_qor(report), top=self.design.get("top"),
                    commands=["report_qor", "report_power"])
        return {"data": data, "text": report[-3000:]}
